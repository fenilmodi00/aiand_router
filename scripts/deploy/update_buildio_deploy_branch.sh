#!/usr/bin/env bash
# Regenerate the digest-pinned `deploy` branch that build.io deploys.
#
# build.io's builder is the failure point (see docs/DEPLOY_BUILDIO.md), so
# production deploys a prebuilt image: this script writes a branch whose
# Dockerfile is only `FROM ghcr.io/...@sha256:...`, so the platform build is
# a pull, not a compile. It also writes a no-op `Test` workflow so build.io's
# required-check gate is satisfied on the deploy branch (the real gate runs
# on `v0` before the image is published).
#
# Safe to run locally or from CI; does not require `gh`. Never force-pushes
# and never touches `v0` or `main`.
#
# Usage:
#   scripts/deploy/update_buildio_deploy_branch.sh --image IMAGE
#       [--branch deploy] [--repo OWNER/REPO] [--dry-run]
#
# Example:
#   scripts/deploy/update_buildio_deploy_branch.sh \
#     --image ghcr.io/fenilmodi00/aiand_router@sha256:abc...64-hex
set -euo pipefail

usage() {
  cat <<'USAGE'
Usage: scripts/deploy/update_buildio_deploy_branch.sh --image IMAGE [--branch deploy] [--repo OWNER/REPO] [--dry-run]

Write the digest-pinned deploy branch that build.io deploys.

  --image IMAGE   Pinned image reference; must match
                  ghcr.io/<repo>@sha256:<64 hex chars> (tags are rejected).
  --branch NAME   Branch to publish. Default: deploy (or DEPLOY_BRANCH).
  --repo ORG/REPO GitHub repository. Default: $GITHUB_REPOSITORY or
                  fenilmodi00/aiand_router.
  --dry-run       Print the generated files to stdout and change nothing.
  -h, --help      Show this help.
USAGE
}

die() { echo "error: $*" >&2; exit 1; }

image=""
branch="${DEPLOY_BRANCH:-deploy}"
repo="${GITHUB_REPOSITORY:-fenilmodi00/aiand_router}"
dry_run=0

while [ $# -gt 0 ]; do
  case "$1" in
    --image)
      [ $# -ge 2 ] || die "--image requires a value"
      image="$2"; shift 2 ;;
    --branch)
      [ $# -ge 2 ] || die "--branch requires a value"
      branch="$2"; shift 2 ;;
    --repo)
      [ $# -ge 2 ] || die "--repo requires a value"
      repo="$2"; shift 2 ;;
    --dry-run)
      dry_run=1; shift ;;
    -h|--help)
      usage; exit 0 ;;
    *)
      usage >&2; die "unknown argument: $1" ;;
  esac
done

[ -n "$image" ] || { usage >&2; die "--image is required"; }
case "$image" in
  ghcr.io/[a-z0-9._/-]@*|ghcr.io/[a-z0-9._/-][a-z0-9._/-]*@sha256:*) ;;
  *) usage >&2; die "--image must be 'ghcr.io/<owner>/<repo>@sha256:<64 hex chars>'; got: $image" ;;
esac
pinned="${image#ghcr.io/}"
pinned_hash="${pinned##*@sha256:}"
[ "${#pinned_hash}" -eq 64 ] || { usage >&2; die "--image digest must be exactly 64 hex chars"; }
short="${pinned_hash:0:12}"

if [ "$dry_run" -eq 1 ]; then
  cat <<EOF
# ---- Dockerfile -------------------------------------------------------------
# Generated by scripts/deploy/update_buildio_deploy_branch.sh — do not edit.
# build.io deploys the prebuilt image built by GitHub Actions (see
# docs/DEPLOY_BUILDIO.md); this build only pulls it. The image MUST stay
# digest-pinned: tags are mutable, the digest is the deployed artifact.
FROM ${image}

# ---- README.md --------------------------------------------------------------
# Generated by scripts/deploy/update_buildio_deploy_branch.sh — do not edit.

# build.io deploy branch
#
# This branch is generated by
# \`scripts/deploy/update_buildio_deploy_branch.sh\` and exists only so
# build.io can deploy a prebuilt image. Its Dockerfile is a single
# \`FROM ghcr.io/fenilmodi00/aiand_router@sha256:${pinned_hash}\` — no
# compilation happens on build.io. Commit \`ci(deploy): point build.io at
# sha256:${short}\` republishes it with a new digest.
#
# The branch also carries a no-op \`.github/workflows/test.yml\` so build.io's
# \`Test\` required-check gate passes; the real test gate runs on \`v0\` before
# the image is published.
#
# Do not edit or push anything else to this branch.

# ---- .github/workflows/test.yml ---------------------------------------------
name: Test
on:
  push:
  pull_request:
jobs:
  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - run: echo "prebuilt image deploy branch; image is verified in the source repo"
EOF
  exit 0
fi

command -v git >/dev/null 2>&1 || die "git is required"
[ -n "${GITHUB_TOKEN:-}" ] && remote_url="https://x-access-token:${GITHUB_TOKEN}@github.com/${repo}.git" \
  || remote_url="https://github.com/${repo}.git"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

git init -q --initial-branch="$branch" "$work"
git -C "$work" remote add origin "$remote_url"

# Reuse the existing deploy branch history when it exists; otherwise start an
# orphan branch. This must happen before writing files: checking out an
# existing branch would overwrite (or be blocked by) them otherwise. A failed
# fetch (missing branch, no network) just means fresh.
if git -C "$work" ls-remote --exit-code --heads origin "$branch" >/dev/null 2>&1; then
  git -C "$work" fetch -q origin "$branch"
  git -C "$work" checkout -q -f -B "$branch" FETCH_HEAD
else
  echo "no existing '$branch' branch on origin; creating a fresh one"
fi

mkdir -p "$work/.github/workflows"

cat >"$work/Dockerfile" <<EOF
# Generated by scripts/deploy/update_buildio_deploy_branch.sh — do not edit.
# build.io deploys the prebuilt image built by GitHub Actions (see
# docs/DEPLOY_BUILDIO.md); this build only pulls it. The image MUST stay
# digest-pinned: tags are mutable, the digest is the deployed artifact.
FROM ${image}
EOF

cat >"$work/README.md" <<EOF
# Generated by scripts/deploy/update_buildio_deploy_branch.sh — do not edit.

# build.io deploy branch

This branch is generated by
\`scripts/deploy/update_buildio_deploy_branch.sh\` and exists only so
build.io can deploy a prebuilt image. Its Dockerfile is a single
\`FROM ghcr.io/fenilmodi00/aiand_router@sha256:${pinned_hash}\` — no
compilation happens on build.io. Commit \`ci(deploy): point build.io at
sha256:${short}\` republishes it with a new digest.

The branch also carries a no-op \`.github/workflows/test.yml\` so build.io's
\`Test\` required-check gate passes; the real test gate runs on \`v0\` before
the image is published.

Do not edit or push anything else to this branch.
EOF

cat >"$work/.github/workflows/test.yml" <<'EOF'
name: Test
on:
  push:
  pull_request:
jobs:
  test:
    name: Test
    runs-on: ubuntu-latest
    steps:
      - run: echo "prebuilt image deploy branch; image is verified in the source repo"
EOF

cd "$work"

if git diff --quiet HEAD -- Dockerfile README.md .github/workflows/test.yml 2>/dev/null \
  && [ -f Dockerfile ] && [ -f README.md ] && [ -f .github/workflows/test.yml ]; then
  echo "already current: '$branch' already pins ${image}"
  exit 0
fi

git add Dockerfile README.md .github/workflows/test.yml
git -c user.name="aiand-router deploy bot" \
    -c user.email="deploy-bot@users.noreply.github.com" \
    commit -q -m "ci(deploy): point build.io at sha256:${short}"

# Plain push, never force: a stale local view must fail loudly instead of
# clobbering a newer digest.
git push -q origin "HEAD:$branch"

echo "pushed '$branch' -> ${image}"
echo
echo "Reminder: the build.io app branch must be set to '${branch}' in the dashboard; this script does not change it."
