#!/usr/bin/env python3
"""Refresh the cluster-assignment cache from the live centroids.

Ticket: the committed `.context/label-runs/prompt-clusters-v082-full.json`
(1,682 entries) predates the final centroid retrain: 150 entries disagree with
the live top-1 cosine route over `internal/router/cluster/artifacts/v0.82/
centroids.bin`, so every builder that trusts it silently mis-assigns prompts.

This script recomputes, for every prompt in the label corpus, the cluster id
the runtime would assign (top-1 cosine of the prompt's embedding against the
centroids) and writes it to `.context/label-runs/prompt-clusters-v084.json`
(flat {global_index: cluster_int}, sorted keys, one line). The v0.82-named
cache is left untouched: several scripts cite it as historical provenance.

Contract parity with the runtime embedder (scripts/bakeoff_v084.py, which the
v0.82/v0.83 builders and the Go Embedder follow): the prompt text is the row's
own `question` field, tail-truncated to 1024 bytes on a UTF-8 boundary,
embedded with masked mean pool + L2 norm over the last 256 token ids, then
compared (cosine) against the L2-normalized centroids from centroids.bin.

The PEM1 embedding cache beside the labels is reused whenever its header's
corpus_sha256 and centroids_sha256 match (same tuples the bake-off writes), so
the ~10-minute embedding only runs when the corpus, the embedder asset or the
centroids change; on a miss the cache is rewritten with the matching keys.

Usage (from the repo root): python scripts/refresh_cluster_assignments.py
"""
from __future__ import annotations

import hashlib
import json
import struct
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from bakeoff_v084 import (  # noqa: E402  (runtime-parity embedding contract)
    EMBEDDER_ASSETS,
    PEM_MAGIC,
    embed_prompts,
    load_centroids,
)

LABELS = REPO / ".context/label-runs/v082-expanded-labels.jsonl"
CENTROIDS = REPO / "internal/router/cluster/artifacts/v0.82/centroids.bin"
EMBED_CACHE = REPO / ".context/label-runs/corpus-embeds-v084.bin"
OLD_ASSIGN = REPO / ".context/label-runs/prompt-clusters-v082-full.json"
OUT = REPO / ".context/label-runs/prompt-clusters-v084.json"
EMBED_DIM = 768
EMBEDDER_ID = "jina-v2-base-code-int8"


def corpus_texts() -> tuple[list[str], dict[str, str]]:
    """(sorted prompt ids, {prompt: question}) — one text per prompt, taken from
    the row's own `question` field."""
    texts: dict[str, str] = {}
    with LABELS.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            texts.setdefault(r["global_index"], r.get("question") or "")
    return sorted(texts), texts


def centroids_sha256() -> str:
    return hashlib.sha256(CENTROIDS.read_bytes()).hexdigest()


def cache_header(n: int, corpus_sha: str, cents_sha: str) -> dict:
    return {
        "embedder_id": EMBEDDER_ID,
        "embed_dim": EMBED_DIM,
        "n": n,
        "corpus_sha256": corpus_sha,
        "centroids_sha256": cents_sha,
        "prompt_order": "sorted(global_index)",
        "comment": "Live cluster-assignment embeddings; regenerated by "
                   "scripts/refresh_cluster_assignments.py.",
    }


def load_or_embed(prompts: list[str], texts: dict[str, str],
                  corpus_sha: str, cents_sha: str) -> np.ndarray:
    """Reuse the committed PEM1 cache when its corpus/centroid fingerprints
    match; otherwise embed fresh and rewrite it with the matching keys."""
    header = cache_header(len(prompts), corpus_sha, cents_sha)
    if EMBED_CACHE.exists():
        raw = EMBED_CACHE.read_bytes()
        hlen = int.from_bytes(raw[4:8], "little") if len(raw) >= 8 else -1
        if len(raw) >= 8 and raw[:4] == PEM_MAGIC and hlen >= 0:
            try:
                old = json.loads(raw[8:8 + hlen])
            except json.JSONDecodeError:
                old = {}
            same = (
                old.get("corpus_sha256") == corpus_sha
                and old.get("centroids_sha256") == cents_sha
                and old.get("embedder_id") == EMBEDDER_ID
                and old.get("embed_dim") == EMBED_DIM
                and old.get("n") == len(prompts)
            )
            if same:
                rows = (len(raw) - 8 - hlen) // (EMBED_DIM * 4)
                if rows == len(prompts):
                    print(f"embeddings: cache hit ({len(prompts)} rows, corpus "
                          f"sha256 {corpus_sha[:12]}, centroids {cents_sha[:12]})")
                    return np.frombuffer(raw[8 + hlen:], dtype="<f4"
                                         ).reshape(len(prompts), EMBED_DIM).copy()
            print("embeddings: cache stale (corpus/embedder/centroids changed); re-embedding")
    print(f"embedding {len(prompts)} prompts (one-time; cached to "
          f"{EMBED_CACHE.relative_to(REPO)})...")
    vecs = embed_prompts([texts[p] for p in prompts]).astype("<f4")
    hb = json.dumps(header, sort_keys=True).encode()
    EMBED_CACHE.parent.mkdir(parents=True, exist_ok=True)
    with EMBED_CACHE.open("wb") as fh:
        fh.write(PEM_MAGIC)
        fh.write(struct.pack("<I", len(hb)))
        fh.write(hb)
        fh.write(vecs.tobytes())
    return vecs


def main() -> int:
    prompts, texts = corpus_texts()
    rows = [json.loads(l) for l in LABELS.read_text(encoding="utf-8").splitlines() if l.strip()]
    print(f"corpus: {len(rows)} rows, {len(prompts)} prompts "
          f"(.context/label-runs/v082-expanded-labels.jsonl)")

    cents = load_centroids(CENTROIDS.parent)
    assert cents.shape == (16, EMBED_DIM), cents.shape
    assert EMBEDDER_ASSETS.is_dir(), EMBEDDER_ASSETS

    corpus_sha = hashlib.sha256(LABELS.read_bytes()).hexdigest()
    cents_sha = centroids_sha256()
    vecs = load_or_embed(prompts, texts, corpus_sha, cents_sha)
    sims = cents @ vecs.T                      # (16, n) cosine; rows are unit
    top1 = np.argmax(sims, axis=0)             # ties -> lowest cluster index
    assign = {p: int(top1[i]) for i, p in enumerate(prompts)}

    OUT.write_text(json.dumps(assign, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(assign)} entries "
          f"(sha256 {hashlib.sha256(OUT.read_bytes()).hexdigest()[:16]}…)")

    pop = {k: 0 for k in range(len(cents))}
    for c in assign.values():
        pop[c] += 1
    print("per-cluster population:", {k: pop[k] for k in sorted(pop)})

    old = json.loads(OLD_ASSIGN.read_text(encoding="utf-8")) if OLD_ASSIGN.exists() else {}
    common = sorted(set(assign) & set(old))
    stale = [p for p in common if int(old[p]) != assign[p]]
    print(f"vs old cache {OLD_ASSIGN.name}: {len(stale)}/{len(common)} common "
          f"entries disagree (old-cache-only: {len(old) - len(common)}, "
          f"new-only: {len(assign) - len(common)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
